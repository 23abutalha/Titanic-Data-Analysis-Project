# CLASS 2 — DataPreprocessor
# ═══════════════════════════════════════════════════════════════════════════════
class DataPreprocessor:
    """Clean and transform a raw Titanic DataFrame."""

    def __init__(self, df: pd.DataFrame):
        self._df = df.copy()
        self._steps_log = []              # audit trail of every step

    # ── public pipeline method ─────────────────────────────────────────────────
    def run_pipeline(self) -> pd.DataFrame:
        """Execute the full preprocessing pipeline and return a clean copy."""
        self._drop_irrelevant_columns()
        self._remove_duplicates()
        self._impute_age()
        self._impute_embarked()
        self._impute_fare()
        self._encode_sex()
        self._type_conversions()
        self._feature_engineering()
        self._filter_outliers()
        return self._df.copy()

    # ── private helpers ────────────────────────────────────────────────────────
    def _drop_irrelevant_columns(self):
        """Drop high-cardinality / ID columns that add no predictive value."""
        cols = [c for c in ['PassengerId','Name','Ticket','Cabin'] if c in self._df.columns]
        self._df.drop(columns=cols, inplace=True)
        self._log(f"Dropped columns: {cols}")

    def _remove_duplicates(self):
        before = len(self._df)
        self._df.drop_duplicates(inplace=True)
        self._log(f"Duplicates removed: {before - len(self._df)}")

    def _impute_age(self):
        """Fill missing Age with median stratified by Pclass & Sex."""
        missing_before = self._df['Age'].isna().sum()
        self._df['Age'] = self._df.groupby(['Pclass','Sex'])['Age'].transform(
            lambda x: x.fillna(x.median())
        )
        # fallback for any remaining
        self._df['Age'].fillna(self._df['Age'].median(), inplace=True)
        self._log(f"Age — imputed {missing_before} missing values (stratified median)")

    def _impute_embarked(self):
        missing = self._df['Embarked'].isna().sum()
        mode_val = self._df['Embarked'].mode()[0]
        self._df['Embarked'].fillna(mode_val, inplace=True)
        self._log(f"Embarked — filled {missing} NaN with mode '{mode_val}'")

    def _impute_fare(self):
        missing = self._df['Fare'].isna().sum()
        if missing:
            self._df['Fare'].fillna(self._df['Fare'].median(), inplace=True)
            self._log(f"Fare — filled {missing} NaN with median")

    def _encode_sex(self):
        """One-hot encode Sex; keep original for EDA."""
        self._df['Sex_Code'] = (self._df['Sex'] == 'female').astype(int)
        self._log("Sex_Code column created (female=1, male=0)")

    def _type_conversions(self):
        self._df['Pclass']   = self._df['Pclass'].astype('category')
        self._df['Survived'] = self._df['Survived'].astype(int)
        self._df['Age']      = self._df['Age'].round(1)
        self._log("Data types cast: Pclass→category, Survived→int, Age→float(1dp)")

    def _feature_engineering(self):
        """Add domain-derived features."""
        self._df['FamilySize']  = self._df['SibSp'] + self._df['Parch'] + 1
        self._df['IsAlone']     = (self._df['FamilySize'] == 1).astype(int)
        self._df['FarePerPerson'] = (self._df['Fare'] / self._df['FamilySize']).round(2)
        self._df['AgeGroup']    = pd.cut(
            self._df['Age'],
            bins=[0, 12, 18, 35, 60, 100],
            labels=['Child','Teen','YoungAdult','Adult','Senior']
        )
        self._log("Feature engineering: FamilySize, IsAlone, FarePerPerson, AgeGroup")

    def _filter_outliers(self):
        """Cap Fare at 99th percentile to reduce skew."""
        cap = self._df['Fare'].quantile(0.99)
        outliers = (self._df['Fare'] > cap).sum()
        self._df['Fare'] = self._df['Fare'].clip(upper=cap)
        self._log(f"Fare outliers capped at 99th-percentile ({cap:.2f}): {outliers} rows affected")

    def _log(self, msg: str):
        self._steps_log.append(msg)

    # ── property ───────────────────────────────────────────────────────────────
    @property
    def pipeline_log(self):
        return self._steps_log


