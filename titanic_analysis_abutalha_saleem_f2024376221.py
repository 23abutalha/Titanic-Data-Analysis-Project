        grp = self._df.groupby(['AgeGroup','Survived'], observed=True).size().unstack(fill_value=0)
        x   = np.arange(len(grp))
        ax.bar(x, grp[0], color=PALETTE[2], alpha=0.9, label='Did Not Survive')
        ax.bar(x, grp[1], bottom=grp[0], color=PALETTE[1], alpha=0.9, label='Survived')
        ax.set_xticks(x); ax.set_xticklabels(grp.index.astype(str), rotation=20)
        ax.legend()
        self._style_ax(ax,'Survival Count by Age Group (Stacked)','Age Group','Count')
        if standalone: plt.tight_layout(); plt.show()

