# CLASS 3 — EDAAnalyzer
# ═══════════════════════════════════════════════════════════════════════════════
class EDAAnalyzer:
    """Compute descriptive statistics and aggregations on the clean DataFrame."""

    def __init__(self, df: pd.DataFrame):
        self._df = df.copy()

    def describe(self) -> pd.DataFrame:
        return self._df.describe(include='all').T

    def missing_report(self) -> pd.DataFrame:
        miss  = self._df.isna().sum()
        pct   = (miss / len(self._df) * 100).round(2)
        return pd.DataFrame({'Missing': miss, 'Pct (%)': pct}).query('Missing > 0')

    def survival_rate(self, groupby_col: str) -> pd.DataFrame:
        grp = self._df.groupby(groupby_col)['Survived']
        return pd.DataFrame({
            'Total':    grp.count(),
            'Survived': grp.sum(),
            'Rate (%)': (grp.mean() * 100).round(1)
        })

    def correlation_matrix(self) -> pd.DataFrame:
        num = self._df.select_dtypes(include=[np.number])
        return num.corr()

    def age_stats(self) -> dict:
        a = self._df['Age']
        return {'mean': a.mean(), 'median': a.median(),
                'std': a.std(), 'min': a.min(), 'max': a.max()}

    def fare_stats(self) -> dict:
        f = self._df['Fare']
        return {'mean': f.mean(), 'median': f.median(),
                'std': f.std(), 'min': f.min(), 'max': f.max()}


