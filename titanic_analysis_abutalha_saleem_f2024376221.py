# CLASS 1 — DataLoader
# ═══════════════════════════════════════════════════════════════════════════════
class DataLoader:
    """Handles dataset ingestion from a local path or a URL."""

    def __init__(self, source: str):
        self.__source = source          # encapsulated attribute
        self._df = None

    # ── public methods ─────────────────────────────────────────────────────────
    def load(self) -> pd.DataFrame:
        """Load CSV and return a raw DataFrame."""
        self._df = pd.read_csv(self.__source)
        return self._df.copy()

    def schema_info(self) -> str:
        """Return a formatted schema summary string."""
        if self._df is None:
            raise RuntimeError("Call load() first.")
        buf = io.StringIO()
        self._df.info(buf=buf)
        return buf.getvalue()

    def head(self, n: int = 5) -> pd.DataFrame:
        return self._df.head(n)

    # ── property (encapsulation) ───────────────────────────────────────────────
    @property
    def source(self) -> str:
        return self.__source

    @property
    def shape(self):
        return self._df.shape if self._df is not None else None


