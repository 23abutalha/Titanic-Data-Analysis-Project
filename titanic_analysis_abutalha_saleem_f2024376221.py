    def _show_summary(self):
        self._chart_frame.pack_forget()
        self._summary_frame.pack(fill='both', expand=True)
        self._summary_text.config(state='normal')
        self._summary_text.delete('1.0','end')

        lines = ["=" * 60, "  DATASET SUMMARY", "=" * 60]
        lines += [f"  Rows     : {len(self._df):,}",
                  f"  Columns  : {len(self._df.columns)}",
                  f"  Survivors: {self._df['Survived'].sum()} "
                  f"({self._df['Survived'].mean()*100:.1f}%)", ""]
        lines += ["  SURVIVAL BY CLASS:", "-" * 40]
        sr = self._eda.survival_rate('Pclass')
        for idx, row in sr.iterrows():
            lines.append(f"  Class {idx}: {row['Survived']}/{row['Total']} "
                         f"({row['Rate (%)']}%)")
        lines += ["", "  SURVIVAL BY SEX:", "-" * 40]
        sr2 = self._eda.survival_rate('Sex')
        for idx, row in sr2.iterrows():
            lines.append(f"  {idx:6s}: {row['Survived']}/{row['Total']} "
                         f"({row['Rate (%)']}%)!")
        lines += ["", "  AGE STATS:", "-" * 40]
        for k,v in self._eda.age_stats().items():
            lines.append(f"  {k:8s}: {v:.2f}")
        lines += ["", "  FARE STATS:", "-" * 40]
        for k,v in self._eda.fare_stats().items():
            lines.append(f"  {k:8s}: {v:.2f}")

        content = chr(10).join(lines)          # chr(10) = newline, no literal \n needed
        self._summary_text.insert('end', content)
        self._summary_text.config(state='disabled')

