# CLASS 4 — Visualizer
# ═══════════════════════════════════════════════════════════════════════════════
class Visualizer:
    """Generate all publication-quality Matplotlib charts."""

    def __init__(self, df: pd.DataFrame, eda: EDAAnalyzer):
        self._df  = df.copy()
        self._eda = eda

    # ── Chart helpers ──────────────────────────────────────────────────────────
    @staticmethod
    def _style_ax(ax, title, xlabel='', ylabel=''):
        ax.set_title(title, fontsize=13, fontweight='bold', pad=10)
        ax.set_xlabel(xlabel)
        ax.set_ylabel(ylabel)
        ax.grid(axis='y', alpha=0.4)
        for spine in ax.spines.values():
            spine.set_visible(False)

    # ── 1. Bar Chart — Survival by Pclass ─────────────────────────────────────
    def plot_survival_by_class(self, ax=None):
        standalone = ax is None
        if standalone: fig, ax = plt.subplots(figsize=(7, 4.5))
        sr = self._eda.survival_rate('Pclass')
        x  = np.arange(len(sr))
        w  = 0.35
        ax.bar(x-w/2, sr['Total'],    w, label='Total',    color=PALETTE[0], alpha=0.9)
        ax.bar(x+w/2, sr['Survived'], w, label='Survived', color=PALETTE[1], alpha=0.9)
        ax.set_xticks(x)
        ax.set_xticklabels([f'Class {c}' for c in sr.index])
        for i,(tot,sur) in enumerate(zip(sr['Total'],sr['Survived'])):
            ax.text(i-w/2, tot+3,  str(tot), ha='center', fontsize=9)
            ax.text(i+w/2, sur+3,  str(sur), ha='center', fontsize=9)
        ax.legend()
        self._style_ax(ax,'Survival Count by Passenger Class','Pclass','Count')
        if standalone: plt.tight_layout(); plt.show()

    # ── 2. Pie Chart — Overall Survival ───────────────────────────────────────
    def plot_survival_pie(self, ax=None):
        standalone = ax is None
        if standalone: fig, ax = plt.subplots(figsize=(5, 5))
        vals   = self._df['Survived'].value_counts()
        labels = ['Did Not Survive', 'Survived']
        colors = [PALETTE[2], PALETTE[1]]
        wedge_props = {'linewidth': 2, 'edgecolor': '#0d1117'}
        ax.pie(vals, labels=labels, colors=colors, autopct='%1.1f%%',
               startangle=140, wedgeprops=wedge_props,
               textprops={'color':'#e6edf3','fontsize':11})
        ax.set_title('Overall Survival Rate', fontsize=13, fontweight='bold')
        if standalone: plt.tight_layout(); plt.show()

    # ── 3. Histogram — Age Distribution ───────────────────────────────────────
    def plot_age_histogram(self, ax=None):
        standalone = ax is None
        if standalone: fig, ax = plt.subplots(figsize=(7, 4.5))
        survived   = self._df[self._df['Survived']==1]['Age']
        not_surv   = self._df[self._df['Survived']==0]['Age']
        ax.hist(not_surv, bins=30, alpha=0.7, color=PALETTE[2], label='Did Not Survive')
        ax.hist(survived, bins=30, alpha=0.7, color=PALETTE[1], label='Survived')
        ax.axvline(self._df['Age'].median(), color='yellow', linestyle='--',
                   linewidth=1.5, label=f'Median Age {self._df["Age"].median():.1f}')
        ax.legend()
        self._style_ax(ax,'Age Distribution by Survival Outcome','Age','Frequency')
        if standalone: plt.tight_layout(); plt.show()

    # ── 4. Bar Chart — Survival Rate by Sex ───────────────────────────────────
    def plot_survival_by_sex(self, ax=None):
        standalone = ax is None
        if standalone: fig, ax = plt.subplots(figsize=(6, 4.5))
        sr   = self._eda.survival_rate('Sex')
        cols = [PALETTE[0], PALETTE[3]]
        bars = ax.bar(sr.index, sr['Rate (%)'], color=cols, alpha=0.9, width=0.4)
        for b,v in zip(bars, sr['Rate (%)']):
            ax.text(b.get_x()+b.get_width()/2, v+1, f'{v}%', ha='center', fontweight='bold')
        self._style_ax(ax,'Survival Rate by Sex (%)','Sex','Survival Rate (%)')
        if standalone: plt.tight_layout(); plt.show()

    # ── 5. Scatter Plot — Age vs Fare (coloured by Survival) ──────────────────
    def plot_age_vs_fare(self, ax=None):
        standalone = ax is None
        if standalone: fig, ax = plt.subplots(figsize=(8, 5))
        for survived, color, label in [(0, PALETTE[2], 'Did Not Survive'),
                                        (1, PALETTE[1], 'Survived')]:
            sub = self._df[self._df['Survived'] == survived]
            ax.scatter(sub['Age'], sub['Fare'], alpha=0.45, s=25,
                       color=color, label=label)
        ax.legend()
        self._style_ax(ax,'Age vs Fare coloured by Survival','Age','Fare (£)')
        if standalone: plt.tight_layout(); plt.show()

    # ── 6. Line Chart — Average Fare Trend by Age Group ──────────────────────
    def plot_fare_trend_by_age_group(self, ax=None):
        standalone = ax is None
        if standalone: fig, ax = plt.subplots(figsize=(7, 4.5))
        trend = self._df.groupby('AgeGroup', observed=True)['Fare'].mean()
        ax.plot(trend.index.astype(str), trend.values, marker='o',
                color=PALETTE[4], linewidth=2.2, markersize=7)
        for x, y in zip(trend.index.astype(str), trend.values):
            ax.text(x, y + 0.5, f'£{y:.1f}', ha='center', fontsize=9)
        self._style_ax(ax,'Average Fare by Age Group','Age Group','Avg Fare (£)')
        if standalone: plt.tight_layout(); plt.show()

    # ── 7. Heatmap — Correlation Matrix (Bonus) ───────────────────────────────
    def plot_correlation_heatmap(self, ax=None):
        standalone = ax is None
        if standalone: fig, ax = plt.subplots(figsize=(8, 6))
        corr = self._eda.correlation_matrix()
        im   = ax.imshow(corr, cmap='coolwarm', vmin=-1, vmax=1)
        ax.set_xticks(range(len(corr))); ax.set_yticks(range(len(corr)))
        ax.set_xticklabels(corr.columns, rotation=45, ha='right', fontsize=8)
        ax.set_yticklabels(corr.columns, fontsize=8)
        for i in range(len(corr)):
            for j in range(len(corr)):
                ax.text(j, i, f'{corr.iloc[i,j]:.2f}',
                        ha='center', va='center', fontsize=7,
                        color='white' if abs(corr.iloc[i,j]) > 0.5 else '#e6edf3')
        plt.colorbar(im, ax=ax, shrink=0.8)
        ax.set_title('Feature Correlation Heatmap', fontsize=13, fontweight='bold')
        if standalone: plt.tight_layout(); plt.show()

    # ── 8. Stacked Bar — Survival by AgeGroup & Pclass ────────────────────────
    def plot_survival_by_agegroup(self, ax=None):
        standalone = ax is None
        if standalone: fig, ax = plt.subplots(figsize=(8, 5))
